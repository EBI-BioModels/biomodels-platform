    File findModelDotGitDirectory(Model model) {
        assert model?.vcsIdentifier: "Model instance having a vcsIdentifier expected"
        assert grailsApp: "Missing grailsApplication bean reference 'grailsApp'. Are you using grails run-script ?"
        def base = grailsApp.config.flatten().get "jummp.vcs.workingDirectory"
        assert base instanceof String
        Paths.get(base, model.vcsIdentifier, ".git").toFile()
    }

    private static String performGitRevert(Repository repository, String ref) throws GitAPIException {
         ObjectId toRevert = Objects.requireNonNull(repository, "Model folder Git repo required")
            .resolve(ref)
        Git git = new Git(repository)
        def newHead = git.revert()
            .include(toRevert)
            .call()
        /* use git.reset().setMode(org.eclipse.jgit.api.ResetCommand.ResetType.HARD)
            .setRef("HEAD^").call() to undo if needed */

       newHead.name
    }

    /*
     * Handles the mechanics of reverting a model revision from the Git repo.
     *
     * You should probably call {@link revertGitRevision(Revision)} instead.
     * @param repository the initialised repository reference for that revision's model.
     * @param revision the revision whose file system changes we should revert
     * @throws GitAPIException if there was an internal error which prevented us from reverting the revision
     * @see {@link revertGitRevision()}
     */
    static void doRevertGitRevision(Repository repository, Revision revision) throws GitAPIException {
        String revisionId = Objects.requireNonNull(revision, "Revision to revert required").vcsId
        String newHead = performGitRevert repository, revisionId
        String msg = "Reverted ${revisionId}. HEAD is now $newHead"
        addModelMsg(revision.model.submissionId, msg)
    }

    private Object withGitRepoForRevision(Revision revision, Closure c) {
        assert revision
        Model model = revision.model
        File baseDir = findModelDotGitDirectory(model)

        Repository repository = GitSupport.buildRepository(baseDir)
        try {
            c.call(repository)
        } finally {
            repository.close()
        }
    }

    /**
     * Convenience method for reverting a revision in a Git repository.
     *
     * @param revision the revision whose file changes should be reverted.
     * @throws GitAPIException if JGit encountered an error while performing the revert command.
     */
    void revertGitRevision(Revision revision) throws GitAPIException {
        withGitRepoForRevision(revision) { Repository repository ->
            doRevertGitRevision(repository, revision)
        }
    }

    /**
     * Atomically deletes a revision, its repository files and associated ACL permissions.
     *
     * <p>Since {@link net.biomodels.jummp.core.ModelService#addValidatedRevision(java.util.List, java.util.List, net.biomodels.jummp.core.model.RevisionTransportCommand)}
     * inserts the new revision in a dedicated transaction which gets committed and flushed before the method returns, we
     * cannot use transaction rollback to undo that insertion &ndash; we need to use another dedicated transaction which
     * undoes that work.</p>
     * <p>We also run <tt>git revert</tt> so that the
     *
     * <p>This method will throw an {@code IllegalStateException} if any of the entities could not be deleted.</p>
     * @param toDelete the revision that should be deleted
     * @see UhlenModelUpdater#rollBackSessionAndRevision(net.biomodels.jummp.model.Revision, org.springframework.orm.hibernate4.SessionHolder)
     */
    void undoRevisionInsertion(Revision toDelete) {
        assert toDelete
        long rId = toDelete.id
        AclUtilService aclUtilService = ctx.getBean "aclUtilService", AclUtilService
        // a revision and its ACLs are inserted in a dedicated transaction, so we cannot simply
        def txSettings = [propagationBehavior: TransactionDefinition.PROPAGATION_NESTED,
                          isolationLevel     : TransactionDefinition.ISOLATION_READ_COMMITTED]
        Revision.withTransaction(txSettings) { TransactionStatus status ->
            try {
                aclUtilService.deleteAcl(toDelete)
                String query = "delete RepositoryFile rf where rf.revision = :revision"

                RepositoryFile.executeUpdate(query, [revision: toDelete])
                toDelete.delete(flush: true)
            } catch (Exception e) {
                // rollback everything in this transaction and notify the callee
                status.setRollbackOnly()
                String msg = "Could not delete Revision $rId: ${e.message}"
                throw new IllegalStateException(msg)
            }
            try {
                // database rollback ok, now try the reverting VCS changes for this revision
                revertGitRevision(toDelete)
            } catch (Exception e) {
                // VCS rollback failed, don't commit the database rollback to preserve consistency
                status.setRollbackOnly()
                String msg = "Could not revert VCS changes introduced by Revision $rId: $e"
                throw new IllegalStateException(msg, e)
            }
        }
    }

    /**
     * Marks the current Hibernate session as rollback only and atomically deletes all entities associated with a revision.
     *
     * <p>To be used as the preferred rollback mechanism in code invoked after the new model revision has been created and
     * persisted into the database via {@code modelService.addValidatedRevision( )}, assuming the insertion has been successful.</p>
     *
     * @param revision the revision which should be deleted
     * @see UhlenModelUpdater#undoRevisionInsertion(net.biomodels.jummp.model.Revision)
     * @see UhlenModelUpdater#markSessionAsRollbackOnly(org.springframework.orm.hibernate4.SessionHolder)
     */
    void rollBackSessionAndRevision(Revision revision, SessionHolder session) {
        markSessionAsRollbackOnly(session)
        undoRevisionInsertion(revision)
    }

    /**
     * Convenience method for performing operations within a Hibernate Session.
     * @param callback a closure defining the work to be done
     * @param submissionFolder the model folder on which to operate
     * @return the result of the work performed, possibly null.
     */
    Object doInSession(Closure callback) {
        // set up a Hibernate session
        PersistenceContextInterceptor persistenceInterceptor = ctx.getBean "persistenceInterceptor", PersistenceContextInterceptor
        SessionHolder session = null
        try {
            persistenceInterceptor?.init()
            session = getCurrentSession()
            callback.call(session)
        } finally {
            if (!session?.rollbackOnly) {
                persistenceInterceptor?.flush()
            }
            persistenceInterceptor?.destroy()
        }
    }

    Revision doInsertNewRevision(String modelId, File modelFolder, Model model) {
        Map<String, Object> revisionData = createRevisionCmdForModelFolder(modelId, modelFolder, model)
        if (!revisionData) { // something went wrong, the error has already been logged
            return null
        }
        RevisionTransportCommand revisionCmd = revisionData.revision as RevisionTransportCommand
        List<RepositoryFileTransportCommand> filesToAdd = revisionData.toAdd as List<RepositoryFileTransportCommand>
        List<RepositoryFileTransportCommand> filesToDelete = revisionData.toDelete as List<RepositoryFileTransportCommand>
        Revision newRevision = null
        ModelService modelService = ctx.getBean "modelService", ModelService
        try {
            modelService.addModellingApproachAsAnnotation(revisionCmd, UhlenScriptSupport.modellingApproach)
            addModelMsg(modelId, "Assigned modelling approach")
            newRevision = modelService.addValidatedRevision(filesToAdd, filesToDelete, revisionCmd)
        } catch (ModelException e) {
            assert markSessionAsRollbackOnly(getCurrentSession()): "Adding revision ${revisionCmd.properties} failed but could not roll back"
            addModelError(modelId, "ModelException thrown when inserting the new revision: $e.message")
        }
        newRevision
    }

