    }

    static boolean markSessionAsRollbackOnly(SessionHolder session) {
        assert session: "Hibernate Session not available. Was persistenceInterceptor.init() called?"
        session.setRollbackOnly()
        session.isRollbackOnly()
    }

    /**
     * Returns the file system location where a given model's files are stored.
     *
     * @param model the model for which to look up the corresponding working directory subfolder.
     * @return a{@link File} denoting the model folder
